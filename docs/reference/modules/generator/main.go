// The module page generator writes docs/reference/modules/<module>.md for each core
// module from its page source, internal/checksandalerts/check_<module>.md or
// internal/checksandalerts/destination_<module>.md, and its description in the code file
// beside it, and writes the index docs/reference/modules/README.md. Run it from the
// repository root with go generate ./docs/reference/modules. The documentation map
// (docs/changing-mmwatchdog/documentation-map.md, "Module pages") owns the rules.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"mmwatchdog/internal/checksandalerts"
	"mmwatchdog/internal/config"
)

// The directories of the page sources, of the generated pages, and of the
// official extra modules, relative to the repository root, with slashes.
const (
	pageSourceDirectory          = "internal/checksandalerts"
	generatedPageDirectory       = "docs/reference/modules"
	officialExtraModuleDirectory = "official_extra_modules"
)

// officialExtraModulePage is the name of an official extra module's page in
// its directory.
const officialExtraModulePage = "README.md"

// The two ways in which a module is used, as its description says.
const (
	usedAsCheck            = "check"
	usedAsAlertDestination = "alert_destination"
)

// generatedFileMarker starts the first line of every generated file.
const generatedFileMarker = "<!-- Generated by go generate ./docs/reference/modules"

// sectionUse says whether a section belongs on the page of one kind of
// module, and whether that page must have it.
type sectionUse string

const (
	sectionNotUsed  sectionUse = "not used"
	sectionOptional sectionUse = "optional"
	sectionRequired sectionUse = "required"
)

// pageSectionRule is one "## " section of a module page: its heading, its
// use on the page of a check module and of a destination module, and
// whether the generator writes it on a core module's page.
type pageSectionRule struct {
	Heading             string
	OnCheckModulePage   sectionUse
	OnDestinationPage   sectionUse
	GeneratedOnCorePage bool
}

// use returns the section's use on the page of a module that is used as
// usedAs.
func (rule pageSectionRule) use(usedAs string) sectionUse {
	if usedAs == usedAsAlertDestination {
		return rule.OnDestinationPage
	}
	return rule.OnCheckModulePage
}

// pageSections are the sections of a module page below its title and
// introduction, in their order on the page. The documentation map's table
// "The sections of a module page" lists the same sections with the same
// uses; a test compares the two.
var pageSections = []pageSectionRule{
	{"Set up", sectionOptional, sectionOptional, false},
	{"Inputs", sectionRequired, sectionRequired, true},
	{"Measurements", sectionOptional, sectionNotUsed, true},
	{"When the check fails, and when it cannot check", sectionRequired, sectionNotUsed, false},
	{"What it sends", sectionNotUsed, sectionRequired, false},
	{"When a delivery fails", sectionNotUsed, sectionRequired, false},
	{"Examples", sectionRequired, sectionRequired, false},
	{"Test the destination", sectionNotUsed, sectionOptional, false},
	{"How it works", sectionOptional, sectionOptional, false},
	{"Errors and what they mean", sectionOptional, sectionOptional, false},
	{"Tested on", sectionRequired, sectionRequired, false},
	{"Why it works this way", sectionRequired, sectionRequired, false},
}

// limitsSection is the section of the configuration files reference on limits on measurements,
// which every generated "## Measurements" section links to, relative to
// docs/reference/modules/.
const limitsSection = "../configuration-files.md#checks-that-measure"

func main() {
	root, err := findRepositoryRoot()
	if err == nil {
		err = writeGeneratedPages(root)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "module page generator:", err)
		os.Exit(1)
	}
}

// findRepositoryRoot returns the directory that holds go.mod, starting at
// the current directory: go generate runs the generator in docs/reference/modules.
func findRepositoryRoot() (string, error) {
	directory, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(directory, "go.mod")); err == nil {
			return directory, nil
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			return "", errors.New("no go.mod in the current directory or its parents; run go generate ./docs/reference/modules from the repository")
		}
		directory = parent
	}
}

// pageSourceFile is the page source of a core module, relative to the
// repository root: its code file with .md in place of .go.
func pageSourceFile(module config.CoreModule) string {
	return pageSourceDirectory + "/" + strings.TrimSuffix(module.CodeFile, ".go") + ".md"
}

// writeGeneratedPages writes every generated file that changed, removes
// generated pages that no core module has any more, and names on standard
// error each core module whose page source is missing.
func writeGeneratedPages(root string) error {
	generated, missingSources, err := generatePages(root)
	if err != nil {
		return err
	}
	for _, module := range missingSources {
		fmt.Fprintf(os.Stderr, "module page generator: core module %s has no page source %s; its page is not generated\n", module.Name, pageSourceFile(module))
	}
	output := filepath.Join(root, filepath.FromSlash(generatedPageDirectory))
	existing, err := filepath.Glob(filepath.Join(output, "*.md"))
	if err != nil {
		return err
	}
	for _, file := range existing {
		if _, keep := generated[filepath.Base(file)]; keep {
			continue
		}
		text, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(text, []byte(generatedFileMarker)) {
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	for name, text := range generated {
		file := filepath.Join(output, name)
		if old, err := os.ReadFile(file); err == nil && bytes.Equal(old, text) {
			continue
		}
		if err := os.WriteFile(file, text, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// generatePages returns the generated files of docs/reference/modules by file name, and
// the core modules that have no page source.
func generatePages(root string) (map[string][]byte, []config.CoreModule, error) {
	generated := map[string][]byte{}
	var missingSources []config.CoreModule
	var problems []error
	for _, module := range config.CoreModules() {
		text, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(pageSourceFile(module))))
		if errors.Is(err, os.ErrNotExist) {
			missingSources = append(missingSources, module)
			continue
		}
		if err != nil {
			return nil, nil, err
		}
		source, err := parsePage(pageSourceFile(module), module.Name, module.UsedAs, true, string(text))
		if err != nil {
			problems = append(problems, err)
			continue
		}
		page, err := renderPage(module, source)
		if err != nil {
			problems = append(problems, err)
			continue
		}
		generated[module.Name+".md"] = []byte(page)
	}
	if len(problems) > 0 {
		return nil, nil, errors.Join(problems...)
	}
	extras, err := officialExtraModules(root)
	if err != nil {
		return nil, nil, err
	}
	generated["README.md"] = []byte(renderIndex(generated, extras))
	return generated, missingSources, nil
}

// officialExtraModules returns the official extra modules of the
// repository, in order of name, each with its description.
func officialExtraModules(root string) ([]checksandalerts.ModuleInfo, error) {
	listed, err := config.ListModules(checksandalerts.ModuleDirs{OfficialExtra: filepath.Join(root, officialExtraModuleDirectory)})
	if err != nil {
		return nil, err
	}
	var extras []checksandalerts.ModuleInfo
	for _, module := range listed {
		if module.Kind != "official_extra" {
			continue
		}
		if module.Description == nil {
			return nil, fmt.Errorf("the official extra module %s: %s", module.Name, module.Problem)
		}
		extras = append(extras, module)
	}
	return extras, nil
}

// pageSource is a module page as its author writes it: its title line, the
// introduction below it, and its sections.
type pageSource struct {
	Title        string
	Introduction string
	Sections     []pageSection
}

// pageSection is one "## " section: its heading without the "## ", and its
// text up to the next "## " heading.
type pageSection struct {
	Heading string
	Text    string
}

// section returns the section with that heading.
func (source pageSource) section(heading string) (pageSection, bool) {
	index := slices.IndexFunc(source.Sections, func(s pageSection) bool { return s.Heading == heading })
	if index < 0 {
		return pageSection{}, false
	}
	return source.Sections[index], true
}

// parsePage splits a module page as its author writes it into its parts and
// checks them: the title is the module's name in backticks, every section is
// one of pageSections for the module's kind, in that order, and the
// required sections are present. A core module's page source has no
// section that the generator writes; an official extra module's page has
// them all. file names the page in each problem.
func parsePage(file, moduleName, usedAs string, corePageSource bool, text string) (pageSource, error) {
	var problems []error
	problem := func(format string, values ...any) {
		problems = append(problems, fmt.Errorf(file+": "+format, values...))
	}
	kind := "a check module's page"
	if usedAs == usedAsAlertDestination {
		kind = "a destination module's page"
	}
	lines := strings.Split(strings.TrimSuffix(text, "\n"), "\n")
	wantTitle := "# `" + moduleName + "`"
	var source pageSource
	if len(lines) == 0 || lines[0] != wantTitle {
		problem("the first line must be the title %s", wantTitle)
		return source, errors.Join(problems...)
	}
	source.Title = lines[0]
	var current *pageSection
	var body []string
	finish := func() {
		joined := strings.Trim(strings.Join(body, "\n"), "\n")
		if current == nil {
			source.Introduction = joined
		} else {
			current.Text = joined
			source.Sections = append(source.Sections, *current)
		}
		body = nil
	}
	headings := make([]string, len(pageSections))
	for i, rule := range pageSections {
		headings[i] = rule.Heading
	}
	lastPosition := -1
	for number, line := range linesOutsideCodeFences(lines[1:]) {
		if !line.outsideCodeFence {
			body = append(body, line.text)
			continue
		}
		if strings.HasPrefix(line.text, "# ") {
			problem("line %d: a page has one title; %q is a second one", number+2, line.text)
		}
		heading, isSection := strings.CutPrefix(line.text, "## ")
		if !isSection {
			body = append(body, line.text)
			continue
		}
		heading = strings.TrimSpace(heading)
		position := slices.Index(headings, heading)
		switch {
		case position < 0:
			problem("%q is not a section of a module page; the documentation map lists them in its table \"The sections of a module page\"", "## "+heading)
		case pageSections[position].use(usedAs) == sectionNotUsed:
			problem("%q is not a section of %s; the documentation map's table \"The sections of a module page\" lists the sections of each kind of module", "## "+heading, kind)
		case corePageSource && pageSections[position].GeneratedOnCorePage:
			problem("the section %q is generated from the module's description; remove it from the page source", "## "+heading)
		case position <= lastPosition:
			problem("the section %q is out of order; the order is: %s", "## "+heading, strings.Join(headings, ", "))
		default:
			lastPosition = position
		}
		finish()
		current = &pageSection{Heading: heading}
	}
	finish()
	for _, rule := range pageSections {
		if rule.use(usedAs) != sectionRequired || corePageSource && rule.GeneratedOnCorePage {
			continue
		}
		if _, present := source.section(rule.Heading); !present {
			problem("the required section %q is missing", "## "+rule.Heading)
		}
	}
	return source, errors.Join(problems...)
}

// markdownLine is one line of a Markdown file, and whether it is outside a
// fenced code block (fence lines themselves count as inside).
type markdownLine struct {
	text             string
	outsideCodeFence bool
}

// codeFence matches a line that opens or closes a fenced code block.
var codeFence = regexp.MustCompile("^ {0,3}(`{3,}|~{3,})")

func linesOutsideCodeFences(lines []string) []markdownLine {
	var marked []markdownLine
	openFence := ""
	for _, line := range lines {
		fence := codeFence.FindStringSubmatch(line)
		switch {
		case openFence == "" && fence != nil:
			openFence = fence[1]
			marked = append(marked, markdownLine{line, false})
		case openFence != "":
			if fence != nil && fence[1][0] == openFence[0] && len(fence[1]) >= len(openFence) && strings.TrimSpace(line[strings.Index(line, fence[1])+len(fence[1]):]) == "" {
				openFence = ""
			}
			marked = append(marked, markdownLine{line, false})
		default:
			marked = append(marked, markdownLine{line, true})
		}
	}
	return marked
}

// The two forms of a link whose target is a path: an inline link
// [text](target "title") and a reference definition [label]: target.
var (
	inlineLinkTarget        = regexp.MustCompile(`\]\(([^()\s]+)((?:\s+"[^"]*")?)\)`)
	referenceDefinitionLine = regexp.MustCompile(`^( {0,3}\[[^\]]+\]:\s+)(\S+)(.*)$`)
)

// replaceLinkTargets calls replace for the target of every link outside code
// fences and code spans, and returns the text with the targets it returns.
func replaceLinkTargets(text string, replace func(target string) string) string {
	lines := strings.Split(text, "\n")
	for number, line := range linesOutsideCodeFences(lines) {
		if !line.outsideCodeFence {
			continue
		}
		if parts := referenceDefinitionLine.FindStringSubmatch(line.text); parts != nil {
			lines[number] = parts[1] + replace(parts[2]) + parts[3]
			continue
		}
		var rewritten strings.Builder
		for _, segment := range splitCodeSpans(line.text) {
			if segment.isCode {
				rewritten.WriteString(segment.text)
				continue
			}
			rewritten.WriteString(inlineLinkTarget.ReplaceAllStringFunc(segment.text, func(link string) string {
				parts := inlineLinkTarget.FindStringSubmatch(link)
				return "](" + replace(parts[1]) + parts[2] + ")"
			}))
		}
		lines[number] = rewritten.String()
	}
	return strings.Join(lines, "\n")
}

// textSegment is a part of a line: inline code, or text around it.
type textSegment struct {
	text   string
	isCode bool
}

// splitCodeSpans splits a line into inline code spans and the text around
// them. A run of backticks without a closing run of the same length is text.
func splitCodeSpans(line string) []textSegment {
	var segments []textSegment
	textStart := 0
	for i := 0; i < len(line); {
		if line[i] != '`' {
			i++
			continue
		}
		run := 1
		for i+run < len(line) && line[i+run] == '`' {
			run++
		}
		closing := findBacktickRun(line, i+run, run)
		if closing < 0 {
			i += run
			continue
		}
		segments = append(segments, textSegment{line[textStart:i], false}, textSegment{line[i : closing+run], true})
		i = closing + run
		textStart = i
	}
	return append(segments, textSegment{line[textStart:], false})
}

// findBacktickRun returns where a run of exactly length backticks starts at
// or after start, or -1.
func findBacktickRun(line string, start, length int) int {
	for i := start; i < len(line); {
		if line[i] != '`' {
			i++
			continue
		}
		run := 1
		for i+run < len(line) && line[i+run] == '`' {
			run++
		}
		if run == length {
			return i
		}
		i += run
	}
	return -1
}

// urlScheme matches a link target that starts with a scheme, such as
// https: or mailto:.
var urlScheme = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9+.-]*:`)

// isPathLink reports whether a link target is a relative path, which may end
// in an anchor; a target that is only an anchor is not.
func isPathLink(target string) bool {
	return target != "" && !urlScheme.MatchString(target) && !strings.HasPrefix(target, "/") && !strings.HasPrefix(target, "#")
}

// pageSourceName matches the file name of a page source and gives the
// module's name.
var pageSourceName = regexp.MustCompile(`^(?:check|destination)_([a-z][a-z0-9_]*)\.md$`)

// linkForGeneratedPage rewrites a link target of a page source, relative to
// internal/checksandalerts/, so that it works from docs/reference/modules/: a page source becomes
// the generated page of its module, beside the page.
func linkForGeneratedPage(target string) string {
	if !isPathLink(target) {
		return target
	}
	linkPath, anchor, hasAnchor := strings.Cut(target, "#")
	resolved := path.Clean(path.Join(pageSourceDirectory, linkPath))
	var rewritten string
	if parts := pageSourceName.FindStringSubmatch(path.Base(resolved)); parts != nil && path.Dir(resolved) == pageSourceDirectory {
		rewritten = parts[1] + ".md"
	} else {
		relative, err := filepath.Rel(filepath.FromSlash(generatedPageDirectory), filepath.FromSlash(resolved))
		if err != nil {
			return target
		}
		rewritten = filepath.ToSlash(relative)
		if strings.HasSuffix(linkPath, "/") {
			rewritten += "/"
		}
	}
	if hasAnchor {
		rewritten += "#" + anchor
	}
	return rewritten
}

// renderPage joins a page source and the module's description into the
// generated page.
func renderPage(module config.CoreModule, source pageSource) (string, error) {
	if module.Description == nil {
		return "", fmt.Errorf("the core module %s has no description", module.Name)
	}
	var page strings.Builder
	fmt.Fprintf(&page, "%s from %s and the module's description in %s/%s. Edit those files, then run go generate ./docs/reference/modules; never edit this file. -->\n", generatedFileMarker, pageSourceFile(module), pageSourceDirectory, module.CodeFile)
	page.WriteString(source.Title + "\n")
	if source.Introduction != "" {
		page.WriteString("\n" + replaceLinkTargets(source.Introduction, linkForGeneratedPage) + "\n")
	}
	for _, rule := range pageSections {
		if rule.use(module.UsedAs) == sectionNotUsed {
			continue
		}
		var text string
		switch {
		case rule.Heading == "Inputs":
			text = renderInputs(module)
		case rule.Heading == "Measurements":
			if len(module.Description.Measurements) == 0 {
				continue
			}
			text = renderMeasurements(module)
		case rule.GeneratedOnCorePage:
			return "", fmt.Errorf("the generator writes no text for the section %q", "## "+rule.Heading)
		default:
			section, present := source.section(rule.Heading)
			if !present {
				continue
			}
			text = replaceLinkTargets(section.Text, linkForGeneratedPage) + "\n"
		}
		page.WriteString("\n## " + rule.Heading + "\n\n" + text)
	}
	return page.String(), nil
}

// renderInputs writes the inputs of a core module: one list item for each,
// with its name, its type or its allowed values, whether it is required,
// and its description. A module that takes one value in place of its
// mapping of inputs describes that value first.
func renderInputs(module config.CoreModule) string {
	d := module.Description
	writer := "A check"
	if module.UsedAs == usedAsAlertDestination {
		writer = "A destination"
	}
	var text strings.Builder
	switch {
	case d.Value == nil && len(d.Inputs) == 0:
		text.WriteString("The module takes no inputs.\n")
	case d.Value != nil && len(d.Inputs) == 0:
		fmt.Fprintf(&text, "The module takes one value, which %s writes after the module's name, and no other input.\n\n", strings.ToLower(writer))
		text.WriteString(inputLine("the value of `"+module.Name+"`", *d.Value, true))
	case d.Value != nil:
		fmt.Fprintf(&text, "%s writes the module's inputs as a mapping below the module's name. In place of the mapping, it can write one value after the name:\n\n", writer)
		text.WriteString(inputLine("the value of `"+module.Name+"`", *d.Value, false))
		text.WriteString("\nThe inputs of the mapping:\n\n")
		for _, input := range d.Inputs {
			text.WriteString(inputLine("`"+input.Name+"`", input, true))
		}
	default:
		for _, input := range d.Inputs {
			text.WriteString(inputLine("`"+input.Name+"`", input, true))
		}
	}
	return text.String()
}

// inputLine writes one input as a list item. sayWhetherRequired is false
// for the value in place of a mapping, which is never required.
func inputLine(name string, input checksandalerts.ModuleInput, sayWhetherRequired bool) string {
	kind := escapeMarkdown(input.Type)
	if len(input.AllowedValues) > 0 {
		var values []string
		for _, value := range input.AllowedValues {
			values = append(values, fmt.Sprintf("`%v`", value))
		}
		kind = joinAlternatives(values)
	}
	if sayWhetherRequired {
		if input.Required {
			kind += "; required"
		} else {
			kind += "; optional"
		}
	}
	return fmt.Sprintf("- %s (%s): %s\n", name, kind, asSentence(input.Description))
}

// renderMeasurements writes the measurements of a core check module, and
// whether a check can set a limit on them, from its registry line. A module
// that is marked neither measures nor limitsOnItsMeasurements reports
// measurements that its check records and takes no limit on.
func renderMeasurements(module config.CoreModule) string {
	var text strings.Builder
	for _, measurement := range module.Description.Measurements {
		fmt.Fprintf(&text, "- `%s` (%s): %s\n", measurement.Name, escapeMarkdown(measurement.Unit), asSentence(measurement.Description))
	}
	const setsALimit = "A check sets a limit on a measurement with `fail_when_measurement_above` or `fail_when_measurement_below`, and fails when a reading passes its limit."
	text.WriteString("\n")
	switch {
	case module.Measures && module.FailsWithoutALimit:
		text.WriteString(setsALimit + " A check without a limit can still fail, as [When the check fails, and when it cannot check](#when-the-check-fails-and-when-it-cannot-check) says, so it may state an `alert_severity` and no limit.")
	case module.Measures:
		text.WriteString(setsALimit + " A check that only records its readings states `only_record_readings: true`, no limit, and no `alert_severity`; it never alerts.")
	case module.LimitsOnItsMeasurements:
		text.WriteString("The module fails a check by itself, and it also reports these measurements. " + setsALimit + " A check with the module always states an `alert_severity`.")
	default:
		// The module's own inputs say when its check fails, such as
		// fail_when_certificate_expires_within of tls.
		text.WriteString("A check takes no limit on these measurements: the module's own inputs say when the check fails. MMWatchdog records the readings.\n")
		return text.String()
	}
	text.WriteString(" The configuration files reference explains limits in [checks that measure a number](" + limitsSection + ").\n")
	return text.String()
}

// joinAlternatives writes "a", "a or b", or "a, b, or c".
func joinAlternatives(values []string) string {
	switch len(values) {
	case 1:
		return values[0]
	case 2:
		return values[0] + " or " + values[1]
	}
	return strings.Join(values[:len(values)-1], ", ") + ", or " + values[len(values)-1] //nolint:nilaway // inputLine calls joinAlternatives only after appending a string for every entry in a nonempty AllowedValues list.
}

// escapeMarkdown keeps a description's plain text plain on a rendered page.
// An asterisk could start emphasis, <name> could read as an HTML tag, and a
// backslash could escape the next character. A word or a quoted text that
// holds one of them, such as /etc/mmwatchdog/<name> or "15 3 * * *", becomes code,
// which both a browser and a terminal show as written. Text that is already
// code stays as it is.
func escapeMarkdown(text string) string {
	var out strings.Builder
	for _, part := range codeSpanOrText.FindAllString(text, -1) {
		if strings.HasPrefix(part, "`") {
			out.WriteString(part)
			continue
		}
		out.WriteString(quotedTextOrWord.ReplaceAllStringFunc(part, func(word string) string {
			if !strings.ContainsAny(word, `<>*\`) {
				return word
			}
			if strings.HasPrefix(word, `"`) {
				return "`" + word + "`"
			}
			start := strings.IndexFunc(word, func(r rune) bool { return !strings.ContainsRune("([{", r) })
			end := strings.LastIndexFunc(word, func(r rune) bool { return !strings.ContainsRune(";,.:)]}", r) }) + 1
			if start < 0 || end <= start {
				return "`" + word + "`"
			}
			return word[:start] + "`" + word[start:end] + "`" + word[end:]
		}))
	}
	return out.String()
}

var (
	codeSpanOrText   = regexp.MustCompile("`[^`]*`|[^`]+")
	quotedTextOrWord = regexp.MustCompile(`"[^"]*"|[^\s"]+`)
)

// asSentence starts a description's text with a capital letter and ends it
// with a period.
func asSentence(text string) string {
	text = strings.TrimSpace(text)
	if text == "" {
		return text
	}
	if first := text[0]; first >= 'a' && first <= 'z' {
		text = string(first-'a'+'A') + text[1:]
	}
	if !strings.HasSuffix(text, ".") {
		text += "."
	}
	return escapeMarkdown(text)
}

// renderIndex writes docs/reference/modules/README.md: the core modules by topic, then
// the official extra modules.
func renderIndex(generated map[string][]byte, extras []checksandalerts.ModuleInfo) string {
	var index strings.Builder
	fmt.Fprintf(&index, "%s from the core modules' page sources %s/check_*.md and %s/destination_*.md, their descriptions in the code files beside them, their topics in the registries %s/checkmodules.go and %s/destinationmodules.go, and from %s/*/module_description.yml. Edit those files, then run go generate ./docs/reference/modules; never edit this file. -->\n",
		generatedFileMarker, pageSourceDirectory, pageSourceDirectory, pageSourceDirectory, pageSourceDirectory, officialExtraModuleDirectory)
	index.WriteString("# Module pages\n\n")
	index.WriteString("Each page describes one module of MMWatchdog: what it checks or where it delivers alerts, its inputs and measurements, examples, how it works, its errors, where it is tested, and why it works this way. `mmwatchdog describe-module NAME` prints the same page in a terminal, on a node or on the machine where the configuration is written.\n\n")
	index.WriteString("A core module is built into the `mmwatchdog` program. The core modules are listed by topic, and after them the official extra modules.\n")
	modules := config.CoreModules()
	for _, topic := range checksandalerts.CoreModuleTopics {
		index.WriteString("\n## " + topic + "\n\n")
		for _, module := range modules {
			if module.Topic != topic {
				continue
			}
			summary := escapeMarkdown(module.Description.Summary)
			if _, hasPage := generated[module.Name+".md"]; hasPage {
				fmt.Fprintf(&index, "- [`%s`](%s.md): %s\n", module.Name, module.Name, summary)
			} else {
				fmt.Fprintf(&index, "- `%s` (its page is not written yet): %s\n", module.Name, summary)
			}
		}
	}
	index.WriteString("\n## Official extra modules\n\n")
	index.WriteString("These modules are Starlark scripts that the MMWatchdog project writes and ships in `official_extra_modules/` of every release. A deploy installs them on every node. Each one's page is the `README.md` in its directory.\n\n")
	for _, module := range extras {
		usedAs := "check"
		if module.Description.UsedAs == usedAsAlertDestination {
			usedAs = "alert destination"
		}
		fmt.Fprintf(&index, "- [`%s`](../../../%s/%s/%s) (%s): %s\n", module.Name, officialExtraModuleDirectory, module.Name, officialExtraModulePage, usedAs, escapeMarkdown(strings.TrimSpace(module.Description.Summary)))
	}
	return index.String()
}
